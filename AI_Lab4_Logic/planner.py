# 4. The warehouse domain
# =============================================================================

LOCATIONS = ["A", "B", "C"]
CONNECTED = [("A", "B"), ("B", "A"), ("B", "C"), ("C", "B")]


def move(x: str, y: str) -> Action:
    return Action(
        name=f"Move({x},{y})",
        pos_pre=[f"At(Robot,{x})"],
        pos_eff=[f"At(Robot,{y})"],
        neg_eff=[f"At(Robot,{x})"],
    )


def pickup(p: str, loc: str) -> Action:
    return Action(
        name=f"PickUp({p},{loc})",
        pos_pre=[f"At(Robot,{loc})", f"At({p},{loc})"],
        neg_pre=[f"Holding({p})"],            # (M2) hand-added assumption A2
        pos_eff=[f"Holding({p})"],
        neg_eff=[f"At({p},{loc})"],
    )


def drop(p: str, loc: str) -> Action:
    return Action(
        name=f"Drop({p},{loc})",
        pos_pre=[f"At(Robot,{loc})", f"Holding({p})"],
        pos_eff=[f"At({p},{loc})"],
        neg_eff=[f"Holding({p})"],
    )


def inspect(loc: str) -> Action:
    """(M4) An irrelevant action used in Test C: it changes the state but can
    never contribute to achieving At(Package,C)."""
    return Action(
        name=f"Inspect({loc})",
        pos_pre=[f"At(Robot,{loc})"],
        pos_eff=[f"Inspected({loc})"],
    )


def warehouse_actions(include_pickup: bool = True,
                      include_inspect: bool = False) -> List[Action]:
    actions = [move(x, y) for x, y in CONNECTED]
    if include_pickup:
        actions += [pickup("Package", loc) for loc in LOCATIONS]
    actions += [drop("Package", loc) for loc in LOCATIONS]
    if include_inspect:
        actions += [inspect(loc) for loc in LOCATIONS]
    return actions


INITIAL = {"At(Robot,A)", "At(Package,A)"}
GOAL = {"At(Package,C)"}


# =============================================================================
# 5. Task 3 -- tests  (M4: hand-written)
# =============================================================================

def run_tests() -> None:

    # ---- Task 0 check: which actions are applicable in I? --------------------
    print("=" * 72)
    print("TASK 0 -- applicability in the initial state")
    print("=" * 72)
    print(f"I = {show(INITIAL)}")
    for a in sorted(warehouse_actions(), key=lambda a: a.name):
        print(f"  {a.name:<22} applicable = {applicable(INITIAL, a)}")
    print()

    # ---- Test A: solvable problem -------------------------------------------
    report("TEST A -- Solvable problem (the original warehouse problem)",
           INITIAL, warehouse_actions(), GOAL)

    # ---- Test B: impossible problem -----------------------------------------
    report("TEST B -- Impossible problem (PickUp removed from the action set)",
           INITIAL, warehouse_actions(include_pickup=False), GOAL)

    # ---- Test C: irrelevant actions -----------------------------------------
    #  C1: the robot alone can reach C -- a 2-action plan exists for At(Robot,C)
    report("TEST C1 -- Robot-only goal At(Robot,C) (for comparison)",
           INITIAL, warehouse_actions(include_inspect=True), {"At(Robot,C)"})

    #  C2: with the same actions, the package goal must still cost 4 actions;
    #      the planner must not confuse At(Robot,C) with At(Package,C).
    result = report("TEST C2 -- Package goal At(Package,C) with irrelevant "
                    "Inspect actions available",
                    INITIAL, warehouse_actions(include_inspect=True), GOAL)

    print("=" * 72)
    print("TEST C2 -- explicit cross-checks")
    print("=" * 72)
    if result is None:
        print("  FAIL: no plan was found for a solvable problem.")
    else:
        final = trace_states(INITIAL, result)[-1][1]
        print(f"  Final state contains At(Package,C) : "
              f"{'At(Package,C)' in final}")
        print(f"  Plan contains a PickUp action      : "
              f"{any('PickUp' in a.name for a in result)}")
        print(f"  Plan contains a Drop action        : "
              f"{any('Drop' in a.name for a in result)}")
        print(f"  Plan contains no Inspect action    : "
              f"{not any('Inspect' in a.name for a in result)}")

        # A plan that merely walks the robot to C must be rejected.
        bogus = [move("A", "B"), move("B", "C")]
        print("\n  Validating the bogus plan [Move(A,B), Move(B,C)] "
              "against goal At(Package,C):")
        validate_plan(INITIAL, bogus, GOAL)

        # A plan that ignores a precondition must also be rejected.
        bogus2 = [move("A", "B"), pickup("Package", "B"),
                  move("B", "C"), drop("Package", "C")]
        print("\n  Validating the 'looks reasonable' plan "
              "[Move(A,B), PickUp(Package,B), Move(B,C), Drop(Package,C)]:")
        validate_plan(INITIAL, bogus2, GOAL)
    print("-" * 72)


if __name__ == "__main__":
    run_tests()
