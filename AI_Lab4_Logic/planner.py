"""
planner.py -- A simple STRIPS-style planning agent.

Laboratory: Logical Reasoning for Planning
Artificial Intelligence (Undergraduate)

-------------------------------------------------------------------------------
PROVENANCE / LLM DISCLOSURE
-------------------------------------------------------------------------------
The core of this file (the `Action` class, `applicable`, `apply_action` and the
breadth-first `plan` function) was GENERATED by a Large Language Model from the
specification quoted in Section 3 of the report (Task 2).

The following parts were WRITTEN OR MODIFIED BY HAND after testing:

  (M1) `validate_plan` -- an independent re-execution / verification routine.
       The LLM was not asked for this; it exists so that the plan is checked by
       code that does not share the search's own state bookkeeping.
  (M2) The negative precondition `not Holding(Package)` on every PickUp action
       (the laboratory text does not state it; see "Assumptions" below).
  (M3) `frozenset`-based visited set + deterministic sorting of successors, so
       that runs are reproducible and the search terminates on cyclic Move
       actions (the first generated version looped on Move(A,B)/Move(B,A)).
  (M4) The three test harnesses in `run_tests()` (Tests A, B, C) and the
       `Inspect` action used as an irrelevant action in Test C.

-------------------------------------------------------------------------------
ASSUMPTIONS
-------------------------------------------------------------------------------
  A1. A state is a SET of ground atoms. Closed-world assumption: any atom not
      present in the state is taken to be false.
  A2. The robot can hold at most one package, encoded as the negative
      precondition  not Holding(p)  on PickUp.  (Hand-added, see M2.)
  A3. Effects are applied as: first delete the negative effects, then add the
      positive effects (as required by the specification).
  A4. The goal is a set of POSITIVE atoms; S entails G iff G is a subset of S.
  A5. All actions are ground (fully instantiated) -- no variable binding or
      unification is performed.
  A6. Every action has unit cost, so BFS returns a shortest plan in the number
      of actions.
-------------------------------------------------------------------------------
"""

from collections import deque
from typing import Dict, FrozenSet, Iterable, List, Optional, Set, Tuple


# =============================================================================
# 1. Actions  (LLM-generated; negative preconditions used per specification)
# =============================================================================

class Action:
    """A ground STRIPS action.

    name        : human readable identifier, e.g. "Move(A,B)"
    pos_pre     : atoms that MUST be in the state
    neg_pre     : atoms that must NOT be in the state
    pos_eff     : atoms added to the state
    neg_eff     : atoms deleted from the state
    """

    def __init__(self,
                 name: str,
                 pos_pre: Iterable[str] = (),
                 neg_pre: Iterable[str] = (),
                 pos_eff: Iterable[str] = (),
                 neg_eff: Iterable[str] = ()):
        self.name = name
        self.pos_pre: Set[str] = set(pos_pre)
        self.neg_pre: Set[str] = set(neg_pre)
        self.pos_eff: Set[str] = set(pos_eff)
        self.neg_eff: Set[str] = set(neg_eff)

    def __repr__(self) -> str:
        return self.name


# -----------------------------------------------------------------------------
# 1a. Logical component:  S |= Preconditions(a) ?
# -----------------------------------------------------------------------------

def applicable(state: Set[str], action: Action) -> bool:
    """Return True iff  state |= Preconditions(action).

    This is the LOGICAL REASONING step of the planner: it asks whether the
    current state entails the action's preconditions.  Nothing about search
    happens here.
    """
    return action.pos_pre <= state and not (action.neg_pre & state)


# -----------------------------------------------------------------------------
# 1b. Transition function:  S' = Apply(S, a)
# -----------------------------------------------------------------------------

def apply_action(state: Set[str], action: Action) -> Set[str]:
    """Return the successor state.  Delete-then-add, as specified.

    Raises ValueError if the action is not applicable, so that a bug in the
    search can never silently fabricate an illegal transition.
    """
    if not applicable(state, action):
        raise ValueError(f"{action.name} is not applicable in {sorted(state)}")
    new_state = set(state)
    new_state -= action.neg_eff      # 1. remove negative effects
    new_state |= action.pos_eff      # 2. add positive effects
    return new_state


# -----------------------------------------------------------------------------
# 1c. Goal test:  S |= G ?
# -----------------------------------------------------------------------------

def satisfies_goal(state: Set[str], goal: Set[str]) -> bool:
    return goal <= state


# =============================================================================
# 2. Search component: breadth-first search over states
# =============================================================================

def plan(initial: Set[str],
         actions: List[Action],
         goal: Set[str]) -> Optional[List[Action]]:
    """Breadth-first search for a shortest sequence of actions achieving `goal`.

    Returns the list of actions, or None if no plan exists (the state space is
    finite here, so exhausting the frontier is a sound proof of impossibility).
    """
    start: FrozenSet[str] = frozenset(initial)

    if satisfies_goal(set(start), goal):
        return []                                   # already solved

    frontier: deque = deque([(start, [])])
    visited: Set[FrozenSet[str]] = {start}          # (M3) cycle prevention

    while frontier:
        state_f, path = frontier.popleft()
        state = set(state_f)

        # (M3) deterministic ordering so that repeated runs give the same plan
        for action in sorted(actions, key=lambda a: a.name):
            if not applicable(state, action):       # <-- logic decides what is possible
                continue
            succ = frozenset(apply_action(state, action))
            if succ in visited:
                continue
            new_path = path + [action]
            if satisfies_goal(set(succ), goal):
                return new_path
            visited.add(succ)                       # <-- search decides what to try
            frontier.append((succ, new_path))

    return None                                     # no plan exists


# =============================================================================
# 3. Trace + independent validation  (M1: hand-written, NOT LLM-generated)
# =============================================================================

def trace_states(initial: Set[str],
                 actions_seq: List[Action]) -> List[Tuple[str, Set[str]]]:
    """Re-execute the plan from scratch and return [(label, state), ...]."""
    states = [("S0", set(initial))]
    state = set(initial)
    for i, action in enumerate(actions_seq, start=1):
        state = apply_action(state, action)
        states.append((f"S{i}", set(state)))
    return states


def validate_plan(initial: Set[str],
                  actions_seq: List[Action],
                  goal: Set[str],
                  verbose: bool = True) -> bool:
    """Independently verify a plan.

    Deliberately does NOT reuse anything the search remembered: it replays the
    plan from the initial state, re-checks every precondition, and re-tests the
    goal at the end.  A plan that "looks reasonable" fails here if any single
    precondition is unsatisfied.
    """
    state = set(initial)
    ok = True
    for i, action in enumerate(actions_seq, start=1):
        missing_pos = action.pos_pre - state
        violated_neg = action.neg_pre & state
        if missing_pos or violated_neg:
            ok = False
            if verbose:
                print(f"  [INVALID] step {i}: {action.name}")
                if missing_pos:
                    print(f"            unsatisfied positive preconditions: "
                          f"{sorted(missing_pos)}")
                if violated_neg:
                    print(f"            violated negative preconditions: "
                          f"{sorted(violated_neg)}")
            break
        state = apply_action(state, action)

    if ok and not satisfies_goal(state, goal):
        ok = False
        if verbose:
            print(f"  [INVALID] final state does not entail the goal; "
                  f"missing {sorted(goal - state)}")

    if ok and verbose:
        print("  [VALID] every precondition satisfied and the goal is entailed.")
    return ok


def show(state: Set[str]) -> str:
    return "{" + ", ".join(sorted(state)) + "}"


def report(title: str,
           initial: Set[str],
           actions: List[Action],
           goal: Set[str]) -> Optional[List[Action]]:
    """Run the planner on a problem and print everything the lab asks for."""
    print("=" * 72)
    print(title)
    print("=" * 72)
    print(f"Initial state I : {show(initial)}")
    print(f"Goal        G : {show(goal)}")
    print(f"Actions       : {', '.join(sorted(a.name for a in actions))}")
    print("-" * 72)

    result = plan(initial, actions, goal)

    if result is None:
        print("Plan found    : NO")
        print("No plan found")
        print("-" * 72)
        print()
        return None

    print("Plan found    : YES")
    print(f"Plan ({len(result)} actions):")
    for i, action in enumerate(result, start=1):
        print(f"  {i}. {action.name}")

    print("\nStates reached after each action:")
    for label, state in trace_states(initial, result):
        print(f"  {label} = {show(state)}")

    print("\nIndependent validation:")
    validate_plan(initial, result, goal)
    print("-" * 72)
    print()
    return result


